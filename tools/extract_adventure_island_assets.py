import sys
import os
import json
import base64

def extract_nes_assets(rom_path, output_json_path):
    with open(rom_path, 'rb') as f:
        data = f.read()

    if data[:4] != b'NES\x1a':
        raise ValueError("Invalid iNES ROM header")

    prg_banks = data[4]
    chr_banks = data[5]
    flags6 = data[6]
    flags7 = data[7]
    mapper = (flags6 >> 4) | (flags7 & 0xF0)

    header_size = 16
    prg_size = prg_banks * 16384
    chr_size = chr_banks * 8192

    prg_data = data[header_size : header_size + prg_size]
    chr_data = data[header_size + prg_size : header_size + prg_size + chr_size]

    print(f"ROM Mapper: {mapper}")
    print(f"PRG ROM size: {len(prg_data)} bytes ({prg_banks} banks)")
    print(f"CHR ROM size: {len(chr_data)} bytes ({chr_banks} banks)")

    # Decode 8x8 CHR tiles into 2bpp pixel arrays (0..3)
    num_tiles = len(chr_data) // 16
    tiles = []
    for t in range(num_tiles):
        tile_bytes = chr_data[t * 16 : (t + 1) * 16]
        pixels = []
        for y in range(8):
            plane0 = tile_bytes[y]
            plane1 = tile_bytes[y + 8]
            row = []
            for x in range(8):
                bit0 = (plane0 >> (7 - x)) & 1
                bit1 = (plane1 >> (7 - x)) & 1
                pixel = (bit1 << 1) | bit0
                row.append(pixel)
            pixels.append(row)
        tiles.append(pixels)

    # Standard NES 64-color Master Palette in RGB
    nes_palette = [
        [0x66,0x66,0x66], [0x00,0x2A,0x88], [0x14,0x12,0xA7], [0x3B,0x00,0xA4],
        [0x5C,0x00,0x7E], [0x6E,0x00,0x40], [0x6C,0x06,0x00], [0x56,0x1D,0x00],
        [0x33,0x35,0x00], [0x0B,0x48,0x00], [0x00,0x52,0x00], [0x00,0x4F,0x08],
        [0x00,0x40,0x4D], [0x00,0x00,0x00], [0x00,0x00,0x00], [0x00,0x00,0x00],

        [0xAD,0xAD,0xAD], [0x15,0x5F,0xD9], [0x42,0x40,0xFF], [0x75,0x27,0xFE],
        [0xA0,0x1A,0xCC], [0xB7,0x1E,0x7B], [0xB5,0x31,0x20], [0x99,0x4E,0x00],
        [0x6B,0x6D,0x00], [0x26,0x87,0x00], [0x00,0x93,0x00], [0x00,0x8F,0x32],
        [0x00,0x7C,0x8D], [0x00,0x00,0x00], [0x00,0x00,0x00], [0x00,0x00,0x00],

        [0xFF,0xFF,0xFF], [0x64,0xB0,0xFF], [0x92,0x90,0xFF], [0xC6,0x76,0xFF],
        [0xF3,0x6A,0xFF], [0xFE,0x6E,0xCC], [0xFE,0x81,0x70], [0xEA,0x9E,0x22],
        [0xBC,0xBE,0x00], [0x78,0xE2,0x00], [0x48,0xEE,0x3B], [0x3B,0xEA,0x88],
        [0x3B,0xCD,0xE5], [0x4D,0x4D,0x4D], [0x00,0x00,0x00], [0x00,0x00,0x00],

        [0xFF,0xFF,0xFF], [0xC0,0xE0,0xFF], [0xD3,0xD2,0xFF], [0xE8,0xC8,0xFF],
        [0xFA,0xC2,0xFF], [0xFF,0xC4,0xEA], [0xFF,0xCC,0xC5], [0xF7,0xD8,0xA5],
        [0xE4,0xE5,0x94], [0xC9,0xF4,0x94], [0xB5,0xF9,0xAC], [0xB0,0xF8,0xCD],
        [0xB0,0xF0,0xF4], [0xB8,0xB8,0xB8], [0x00,0x00,0x00], [0x00,0x00,0x00]
    ]

    extracted_data = {
        "mapper": mapper,
        "prg_banks": prg_banks,
        "chr_banks": chr_banks,
        "num_tiles": num_tiles,
        "rom_b64": base64.b64encode(data).decode('ascii'),
        "nes_palette": nes_palette
    }

    os.makedirs(os.path.dirname(output_json_path), exist_ok=True)
    with open(output_json_path, 'w') as out_f:
        json.dump(extracted_data, out_f)

    print(f"Extracted ROM metadata and base64 payload to {output_json_path}")

if __name__ == '__main__':
    rom_file = sys.argv[1] if len(sys.argv) > 1 else 'assets/adventure_island_2/Adventure Island II (USA) (Beta).nes'
    out_file = sys.argv[2] if len(sys.argv) > 2 else 'assets/adventure_island_2/rom_data.json'
    extract_nes_assets(rom_file, out_file)
